-- HomeShare - schema inicial (baseado no ER v4).
-- Regras que o banco não garante (mesma casa, líder ativo, sobreposição de reservas...)
-- ficam nos Services.

CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    senha_hash     VARCHAR(255) NOT NULL,
    data_cadastro  TIMESTAMP    NOT NULL,
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

CREATE TABLE casa (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    criador_id    BIGINT       NOT NULL REFERENCES usuario (id),
    lider_id      BIGINT       NOT NULL REFERENCES usuario (id),
    status        VARCHAR(20)  NOT NULL,
    data_criacao  TIMESTAMP    NOT NULL,
    CONSTRAINT ck_casa_status CHECK (status IN ('ATIVA', 'ENCERRADA'))
);
CREATE INDEX idx_casa_lider ON casa (lider_id);

CREATE TABLE membro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      NOT NULL REFERENCES usuario (id),
    casa_id       BIGINT      NOT NULL REFERENCES casa (id),
    status        VARCHAR(20) NOT NULL,
    data_entrada  TIMESTAMP   NOT NULL,
    data_saida    TIMESTAMP,
    CONSTRAINT uq_membro_usuario_casa UNIQUE (usuario_id, casa_id),
    CONSTRAINT ck_membro_status CHECK (status IN ('ATIVO', 'EXPULSO', 'SAIU'))
);
CREATE INDEX idx_membro_casa_status ON membro (casa_id, status);

CREATE TABLE espaco (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL,
    tipo     VARCHAR(20)  NOT NULL,
    casa_id  BIGINT       NOT NULL REFERENCES casa (id),
    CONSTRAINT ck_espaco_tipo CHECK (tipo IN ('LAVANDERIA', 'CHURRASQUEIRA', 'SALA', 'OUTRO'))
);
CREATE INDEX idx_espaco_casa ON espaco (casa_id);

CREATE TABLE evento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo      VARCHAR(100) NOT NULL,
    data        DATE         NOT NULL,
    horario     TIME         NOT NULL,
    descricao   VARCHAR(500) NOT NULL,
    criado_por  BIGINT       NOT NULL REFERENCES membro (id),
    casa_id     BIGINT       NOT NULL REFERENCES casa (id)
);
CREATE INDEX idx_evento_casa_data ON evento (casa_id, data);

CREATE TABLE aviso (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recado            VARCHAR(500) NOT NULL,
    data_publicacao   TIMESTAMP    NOT NULL,
    autor_id          BIGINT       NOT NULL REFERENCES membro (id),
    casa_id           BIGINT       NOT NULL REFERENCES casa (id)
);
CREATE INDEX idx_aviso_casa_data ON aviso (casa_id, data_publicacao DESC);

CREATE TABLE tarefa (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(100) NOT NULL,
    descricao        VARCHAR(500) NOT NULL,
    prazo            TIMESTAMP    NOT NULL,
    prioridade       VARCHAR(20)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    data_criacao     TIMESTAMP    NOT NULL,
    data_conclusao   TIMESTAMP,
    responsavel_id   BIGINT       NOT NULL REFERENCES membro (id),
    concluido_por    BIGINT       REFERENCES membro (id),
    casa_id          BIGINT       NOT NULL REFERENCES casa (id),
    CONSTRAINT ck_tarefa_prioridade CHECK (prioridade IN ('URGENTE', 'NORMAL', 'TRANQUILA')),
    CONSTRAINT ck_tarefa_status CHECK (status IN ('PENDENTE', 'CONCLUIDA', 'CANCELADA')),
    -- CONCLUIDA <=> data_conclusao e concluido_por preenchidos
    CONSTRAINT ck_tarefa_conclusao CHECK (
        (status = 'CONCLUIDA' AND data_conclusao IS NOT NULL AND concluido_por IS NOT NULL)
        OR (status <> 'CONCLUIDA' AND data_conclusao IS NULL AND concluido_por IS NULL)
    )
);
CREATE INDEX idx_tarefa_casa_status ON tarefa (casa_id, status);
CREATE INDEX idx_tarefa_responsavel ON tarefa (responsavel_id);

CREATE TABLE convite (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(20) NOT NULL,
    validade      TIMESTAMP   NOT NULL,
    status        VARCHAR(20) NOT NULL,
    data_criacao  TIMESTAMP   NOT NULL,
    gerado_por    BIGINT      NOT NULL REFERENCES membro (id),
    casa_id       BIGINT      NOT NULL REFERENCES casa (id),
    usado_por     BIGINT      REFERENCES membro (id),
    data_uso      TIMESTAMP,
    CONSTRAINT uq_convite_codigo UNIQUE (codigo),
    CONSTRAINT ck_convite_status CHECK (status IN ('ATIVO', 'CANCELADO'))
);
CREATE INDEX idx_convite_casa ON convite (casa_id);

CREATE TABLE item_faltando (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL,
    quantidade      INTEGER,
    status          VARCHAR(20)  NOT NULL,
    adicionado_por  BIGINT       NOT NULL REFERENCES membro (id),
    comprado_por    BIGINT       REFERENCES membro (id),
    data_compra     TIMESTAMP,
    casa_id         BIGINT       NOT NULL REFERENCES casa (id),
    CONSTRAINT ck_item_status CHECK (status IN ('FALTANDO', 'COMPRADO')),
    CONSTRAINT ck_item_quantidade CHECK (quantidade IS NULL OR quantidade > 0)
);
CREATE INDEX idx_item_casa_status ON item_faltando (casa_id, status);

CREATE TABLE reserva (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espaco_id       BIGINT      NOT NULL REFERENCES espaco (id),
    reservado_por   BIGINT      NOT NULL REFERENCES membro (id),
    inicio          TIMESTAMP   NOT NULL,
    fim             TIMESTAMP   NOT NULL,
    status          VARCHAR(20) NOT NULL,
    CONSTRAINT ck_reserva_status CHECK (status IN ('ATIVA', 'CANCELADA')),
    CONSTRAINT ck_reserva_periodo CHECK (fim > inicio)
);
CREATE INDEX idx_reserva_espaco_periodo ON reserva (espaco_id, inicio, fim);

CREATE TABLE gasto_fixo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao       VARCHAR(150)   NOT NULL,
    valor_total     NUMERIC(12, 2) NOT NULL,
    mes_referencia  DATE           NOT NULL,
    casa_id         BIGINT         NOT NULL REFERENCES casa (id),
    CONSTRAINT ck_gasto_valor CHECK (valor_total > 0)
);
CREATE INDEX idx_gasto_casa_mes ON gasto_fixo (casa_id, mes_referencia);

CREATE TABLE gasto_morador (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membro_id       BIGINT         NOT NULL REFERENCES membro (id),
    gasto_fixo_id   BIGINT         NOT NULL REFERENCES gasto_fixo (id) ON DELETE CASCADE,
    valor_parcela   NUMERIC(12, 2) NOT NULL,
    pago            BOOLEAN        NOT NULL DEFAULT FALSE,
    data_pagamento  TIMESTAMP,
    CONSTRAINT uq_gasto_morador UNIQUE (gasto_fixo_id, membro_id),
    CONSTRAINT ck_gasto_morador_valor CHECK (valor_parcela >= 0)
);
CREATE INDEX idx_gasto_morador_membro ON gasto_morador (membro_id);

CREATE TABLE regra_casa (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo             VARCHAR(100)  NOT NULL,
    texto              VARCHAR(1000) NOT NULL,
    data_atualizacao   TIMESTAMP     NOT NULL,
    casa_id            BIGINT        NOT NULL REFERENCES casa (id)
);
CREATE INDEX idx_regra_casa ON regra_casa (casa_id);

CREATE TABLE contato (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL,
    funcao    VARCHAR(60)  NOT NULL,
    telefone  VARCHAR(20)  NOT NULL,
    casa_id   BIGINT       NOT NULL REFERENCES casa (id)
);
CREATE INDEX idx_contato_casa ON contato (casa_id);
